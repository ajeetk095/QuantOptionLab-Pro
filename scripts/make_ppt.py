prs = Presentation()
prs.slide_width = Inches(13.333)
prs.slide_height = Inches(7.5)

for i, (title, body) in enumerate(SLIDES):
    slide = prs.slides.add_slide(prs.slide_layouts[6])  # blank
    # accent bar
    bar = slide.shapes.add_shape(1, Inches(0), Inches(0), Inches(0.18), Inches(7.5))
    bar.fill.solid(); bar.fill.fore_color.rgb = PRIMARY; bar.line.fill.background()

    tb = slide.shapes.add_textbox(Inches(0.7), Inches(0.5), Inches(12.0), Inches(1.2))
    tf = tb.text_frame; tf.word_wrap = True
    p = tf.paragraphs[0]; run = p.add_run(); run.text = title
    run.font.size = Pt(40); run.font.bold = True; run.font.color.rgb = PRIMARY

    bb = slide.shapes.add_textbox(Inches(0.75), Inches(1.9), Inches(11.9), Inches(5.2))
    bf = bb.text_frame; bf.word_wrap = True
    for j, line in enumerate(body.split("\n")):
        para = bf.paragraphs[0] if j == 0 else bf.add_paragraph()
        run = para.add_run(); run.text = line
        run.font.size = Pt(20 if i == 0 else 18)
        run.font.color.rgb = DARK if line.startswith("•") else GRAY
        para.space_after = Pt(10)

    # footer
    fb = slide.shapes.add_textbox(Inches(0.75), Inches(7.0), Inches(11.9), Inches(0.4))
    fp = fb.text_frame.paragraphs[0]
    fr = fp.add_run(); fr.text = f"OptionLab Pro · Ajeet Kumar · MScFE 620 GWP#2 · Slide {i+1}/15"
    fr.font.size = Pt(10); fr.font.color.rgb = GRAY

prs.save("ppt/OptionLab_Pro_Presentation.pptx")
print("Saved ppt/OptionLab_Pro_Presentation.pptx with", len(prs.slides.__iter__.__self__._sldIdLst), "slides")
